#!/usr/bin/env python3
"""Independent audit of heesch-sat witness patches, on any grid in lib/heesch/grids.json.

Reads the text output of `sat -show` and re-checks every patch without any solver code: congruence,
no overlap, corona structure, and (for the strict Heesch number) that each prefix of coronas is a
closed topological disk.

A grid is one table (generated by gen_grids.py from the solver's own grid classes): a translation
lattice, and one cell per translation class with its corners as offsets from the cell's point. Cells
are integer points in the solver's coordinates, and which cells touch is read off shared corners
instead of being listed, so every grid shares every line below.

Usage: check_witness.py <sat-output.txt>
"""
import json
import pathlib
import sys

GRIDS = json.loads((pathlib.Path(__file__).resolve().parents[2] / "lib/heesch/grids.json").read_text())
BY_PREFIX = {g["prefix"]: name for name, g in GRIDS.items() if g["prefix"]}


def key(x, y):
    """A corner as a dictionary key. Corners are multiples of 1/12 on every grid but one (4.8.8 has
    √2 in them), and four decimals separates either kind."""
    return (round(x * 10000), round(y * 10000))


class Grid:
    def __init__(self, name):
        g = GRIDS[name]
        self.name, self.den = name, g["den"]
        (ax, ay), (bx, by) = g["period"]
        det = ax * by - ay * bx

        def reduce(p):
            u, v = (p[0] * by - p[1] * bx) // det, (ax * p[1] - ay * p[0]) // det
            return (p[0] - u * ax - v * bx, p[1] - u * ay - v * by)

        self.kind = reduce
        self.kinds = {tuple(c["at"]): [(x / self.den, y / self.den) for x, y in c["verts"]] for c in g["cells"]}
        # Per kind of cell: the offsets to every cell sharing a corner (`touch`) or an edge (`edge`).
        reach = 2 * max(abs(c) for v in g["period"] for c in v) + 2
        self.touch, self.edge = {}, {}
        for at in self.kinds:
            mine = {key(*v) for v in self.verts(at)}
            shared = {}
            for dx in range(-reach, reach + 1):
                for dy in range(-reach, reach + 1):
                    q = (at[0] + dx, at[1] + dy)
                    if (dx, dy) != (0, 0) and self.is_cell(q):
                        n = len(mine & {key(*v) for v in self.verts(q)})
                        if n:
                            shared[(dx, dy)] = n
            self.touch[at] = list(shared)
            self.edge[at] = [d for d, n in shared.items() if n >= 2]

    def is_cell(self, p):
        return self.kind(p) in self.kinds

    def verts(self, p):
        return [(p[0] + vx, p[1] + vy) for vx, vy in self.kinds[self.kind(p)]]

    def near(self, p, table):
        return [(p[0] + dx, p[1] + dy) for dx, dy in table[self.kind(p)]]

    @staticmethod
    def place(t, p):
        a, b, c, d, e, f = t
        return (a * p[0] + b * p[1] + c, d * p[0] + e * p[1] + f)

    def connected(self, cells):
        cells = set(cells)
        seen, stack = set(), [next(iter(cells))]
        while stack:
            p = stack.pop()
            if p in seen:
                continue
            seen.add(p)
            stack += [q for q in self.near(p, self.edge) if q in cells]
        return len(seen) == len(cells)

    def is_disk(self, cells):
        """Edge-connected, and so is the collar of cells touching it: no hole and no pinch point.
        A hole or a pinch cuts the collar in two, because the collar follows the boundary curve."""
        collar = {q for p in cells for q in self.near(p, self.touch)} - cells
        return self.connected(cells) and self.connected(collar)


def audit(grid, shape, tiles, strict):
    errs = []
    placed = []
    for level, t in tiles:
        cells = set()
        for p in shape:
            q = grid.place(t, p)
            # A copy is congruent when every cell lands on a cell, corners on corners.
            if not grid.is_cell(q) or {key(*grid.place(t, v)) for v in grid.verts(p)} != {key(*v) for v in grid.verts(q)}:
                errs.append(f"transform {t} is not a symmetry of the grid")
                break
            cells.add(q)
        placed.append((level, cells))
    if errs:
        return 0, errs
    owner = {}
    for i, (_, cells) in enumerate(placed):
        for p in cells:
            if p in owner:
                errs.append(f"tiles {owner[p]} and {i} overlap at {p}")
            owner[p] = i
    top = max(level for level, _ in placed)
    if [lv for lv, _ in placed].count(0) != 1:
        errs.append("patch must have exactly one centre tile")
    for i, (level, cells) in enumerate(placed):
        halo = {q for p in cells for q in grid.near(p, grid.touch)} - cells
        near = {placed[owner[p]][0] for p in halo if p in owner}
        if level < top and not halo <= owner.keys():
            errs.append(f"tile {i} (corona {level}) is not fully surrounded")
        if level > 0 and level - 1 not in near:
            errs.append(f"tile {i} (corona {level}) touches no corona-{level - 1} tile")
        if any(lv < level - 1 for lv in near):
            errs.append(f"tile {i} (corona {level}) touches a corona below {level - 1}")
    for k in range(top + 1 if strict else top):
        union = set().union(*(cells for level, cells in placed if level <= k))
        if not grid.is_disk(union):
            errs.append(f"coronas 0..{k} do not form a closed disk")
    return top, errs


def records(path):
    """Yield (grid, shape, kind, hc, hh, claims) per record; claims is [(H, strict, tiles)] for non-tilers."""
    lines = [ln.split() for ln in open(path) if ln.strip()]
    grids = {}
    i = 0
    while i < len(lines):
        name = BY_PREFIX[lines[i][0][0]]
        grid = grids.setdefault(name, Grid(name))
        coords = list(map(int, lines[i][1:]))
        shape = sorted(zip(coords[::2], coords[1::2]))
        kind, *rest = lines[i + 1]
        i += 2
        patches = []
        while i < len(lines) and lines[i][0].isdigit():
            n = int(lines[i][0])
            patches.append([(int(r[0]), tuple(map(int, r[1].strip("<>").split(",")))) for r in lines[i + 1:i + 1 + n]])
            i += 1 + n
        if kind != "~":  # tilers and inconclusive shapes carry no Heesch witness
            yield grid, shape, kind, None, None, []
            continue
        hc, hh = int(rest[0]), int(rest[1])
        # A trivial 0-corona is not written out, so an (Hc=0, Hh=1) record holds only the Hh patch.
        claims = [(hc, True)] * (hc > 0) + [(hh, False)] * (hh != hc)
        assert len(claims) == len(patches), f"record (Hc={hc}, Hh={hh}) has {len(patches)} patches"
        yield grid, shape, kind, hc, hh, [(want, strict, tiles) for (want, strict), tiles in zip(claims, patches)]


def audit_claim(grid, shape, want, strict, tiles):
    top, errs = audit(grid, shape, tiles, strict)
    if not errs and top != want:
        errs.append(f"patch has {top} coronas, record claims {want}")
    return errs


def main(path):
    bad = 0
    for grid, shape, _, _, _, claims in records(path):
        for want, strict, tiles in claims:
            errs = audit_claim(grid, shape, want, strict, tiles)
            kind = "strict" if strict else "holes allowed in outer corona"
            print(f"{len(shape)}-{grid.name}, H={want} ({kind}), {len(tiles)} tiles: {'PASS' if not errs else 'FAIL'}")
            for err in errs[:10]:
                print("   ", err)
            bad += bool(errs)
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main(sys.argv[1])
