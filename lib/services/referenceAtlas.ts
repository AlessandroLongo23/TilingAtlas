// The card / search label for a freedraw pattern: what its faces ARE, since there is no vertex
// configuration to name it by. "1 strip + 2 polyominoes", "1 unbounded · holes". The finite noun
// follows the grid: polyomino on squares, polyiamond on triangles, polyhex on hexagons, polyform on
// the combined grid (where the cells are not all one shape, so no -omino word fits), polydrafter on
// the Schwarz 236 board (a 30-60-90 triangle is a drafter).
const FREEDRAW_FINITE_NOUN: Record<FreedrawCatalogueGrid, readonly [string, string]> = {
	square: ["polyomino", "polyominoes"],
	triangle: ["polyiamond", "polyiamonds"],
	hex: ["polyhex", "polyhexes"],
	ts: ["polyform", "polyforms"],
	sch236: ["polydrafter", "polydrafters"],
	// A 45-45-90 triangle is a "abolo" — the (2,4,4) board's tile, and the standard name for a
	// half-square polyform (Gardner, 1967).
	sch244: ["polyabolo", "polyaboloes"],
};
export function freedrawFamilyLabel(s: FreedrawStats, grid: FreedrawGrid = "square"): string {
	const noun = FREEDRAW_FINITE_NOUN[grid];
	const parts: string[] = [];
	if (s.finite) parts.push(`${s.finite} ${s.finite === 1 ? noun[0] : noun[1]}`);
	if (s.strips) parts.push(`${s.strips} ${s.strips === 1 ? "strip" : "strips"}`);
	if (s.unbounded) parts.push(`${s.unbounded} unbounded`);
	return (parts.join(" + ") || "empty") + (s.withHoles ? " · holes" : "");
}

// The star folds present in a family (unique, ascending). "3.4*.6*" → [4,6]. Empty for regular.
export function starFoldsOf(t: Pick<ReferenceTiling, "family">): number[] {
	const folds = new Set<number>();
	for (const tok of t.family.split(".")) {
		if (tok.endsWith("*")) {
			const n = parseInt(tok, 10);
			if (Number.isFinite(n)) folds.add(n);
		}
	}
	return [...folds].sort((a, b) => a - b);
}

