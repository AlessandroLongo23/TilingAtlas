// The Reference (Oracle) shelf — a DISPLAY-ONLY atlas of known k-uniform tilings from the literature,
// deliberately kept OFF the certified-results catalogue (§0: the site never produces the claim; these
// are external oracles, not our search output). Generated by scripts/build-reference-atlas.ts into the
// static asset public/reference-atlas.json and lazy-fetched only when the shelf is opened.
//
//   - galebach: regular k=1..6 (Soto-Sánchez/Galebach), reconstructed geometry. No completeness proof.
//   - myers:    Myers star tilings (k=1 in-ring Fig-4 subclass today; k=2 pending the machine-readable
//               JSON). An unchecked hand enumeration — shown as reference, never as certified.
//   - ctrnact:  Marek Čtrnáct's k-uniform search, reproduced here (k=7 shown; k≤8 in figures/data/ctrnact.json).
//               An unproven exhaustive search extending Galebach beyond k=6 — reference, never certified.
//   - ctrnact-star: the Čtrnáct-engine star extension's full in-ring catalogs (feat/ctrnact-star),
//               k=1..2, star-bearing solutions only. Most reproduce Myers records; the ones flagged
//               candidate:true match NOTHING in Myers and are pending adversarial review.
//   - composable: source tag for the convex-irregular shelf (kept as historical provenance; the
//               user-facing class is "convex", see TileClass). Tilings using convex unit-edge super-tiles
//               (e.g. cx4-2.4.2.4) alongside the regular set (scripts/build-composable-atlas.ts → the
//               separate public/reference-atlas-composable.json). Distinct-tiling counts are EXACT
//               (proof-grade ℤ[ζ₂₄] congruence dedup, NOTES §55); enumeration completeness rests on the
//               engine, as for the regular family. These carry no certification / wallpaper classification.
export type Certification = "proven" | "reproduced" | "candidate";

export interface ReferenceTiling {
	id: string; // "t4001" (galebach) | "myers-k1-star-03" (myers) | "ctrnact-07_..." (ctrnact)
	source: "galebach" | "myers" | "ctrnact" | "ctrnact-star" | "composable" | "isotoxal" | "mixed" | "scaled" | "polyomino" | "islamic" | "freedraw" | "colors" | "hyperbolic" | "spherical" | "hollow";
	k: number;
	family: string; // distinct polygon-type label, e.g. "3.4.6.12"; star tiles marked "n*"
	renderCell: TranslationalCellData; // float, parseBaseCell-ready (a throwaway cell for hyperbolic entries — never drawn)
	// Hollow shelf only: a tiling by SELF-INTERSECTING regular star polygons {n/d}, where the
	// crossings are NOT vertices (Grünbaum-Miller-Shephard, Uniform Tilings with Hollow Tiles, 1981).
	// A different tile from the concave isotoxal |n/d| the `star`/`isotoxal` shelves carry. Its faces
	// overlap by construction, so there is no cell polygon list the flat renderer could consume:
	// `renderCell` is a throwaway here and never drawn, and its presence routes /play + the thumbnails
	// to the hollow renderer (components/hollow-canvas.tsx) the way `freedraw` routes to the grid view.
	// `density` is the constant areal winding number (may be negative or zero — that is the point of a
	// hollow tiling, not a bug); `gms` is the Grünbaum-Miller-Shephard figure number when the tiling is
	// one of theirs; `k` is 1 throughout (uniform only so far).
	hollow?: HollowPattern;
	// Hyperbolic shelf only: the Schläfli symbol {p,q} of a regular hyperbolic tiling. Kept as the card
	// label for the regular entries; routing keys on `developed`. Absent (and geometry "euclidean"/undefined)
	// for every Euclidean tiling.
	schlafli?: [number, number];
	// Hyperbolic shelf: the id of a developed Poincaré patch in public/hyperbolic-developed.json (from the
	// Čtrnáct SU(1,1) developer, tools/ctrnact-oracle/develop_hyperbolic.py). Its presence routes /play +
	// thumbnails to the explicit-geometry renderer (components/hyperbolic-developed-canvas.tsx), which
	// re-develops the tiling from the patch's baked darts, centred on the view, filling the disk to the rim.
	// Every hyperbolic catalogue entry carries it.
	developed?: { patch: string };
	// Hyperbolic shelf: the forced edge length ℓ of the developed patch (the ℓ solving Σ α(pᵢ,ℓ)=2π),
	// merged from public/hyperbolic-developed.json at load. Always a scalar — one edge length per tiling,
	// even at k>1 — and the coordinate that distinguishes members of a family, since H² has no similarity.
	edge?: number;
	// Spherical shelf only: the Schläfli symbol {p,q} of a Platonic solid rendered as a spherical tiling
	// (the finite, 1/p + 1/q > 1/2 end of the regular {p,q} family). Its presence — like developed for the
	// hyperbolic disk — routes /play + the thumbnails to the three.js sphere renderer
	// (components/spherical-canvas.tsx). Absent for every Euclidean and hyperbolic tiling.
	// `solid` (required) is the stable Polyhedron id the renderer routes on — Platonic AND Archimedean
	// solids resolve by it (Archimedean have no {p,q}). p/q are the Schläfli symbol, present for the
	// Platonic solids only (display).
	spherical?: { p?: number; q?: number; solid: string };
	// Freedraw shelf only: the periodic edge subset of the square grid this entry IS (lib/freedraw/pattern.ts).
	// Its presence routes /play + the thumbnails to the 2D grid renderer, the way `developed` routes to the
	// Poincaré disk — freedraw has no polygon cell at all (an infinite strip has no vertex list, an annulus
	// is not star-shaped), so `renderCell` is a throwaway here and is never drawn.
	//
	// CAVEAT ON k. For a freedraw entry `k` counts GRID-POINT orbits of the decoration, including grid points
	// with no drawn edge — NOT vertex orbits of a uniform tiling. It shares the k axis with everything else
	// so the two are browsable together, but every surface that shows it (card sub-line, /play nav header +
	// info panel, the catalogue tree's k rows) must say "grid points", never "vertices".
	freedraw?: FreedrawPattern;
	// Colored-tiling shelf only: a periodic 2-coloring of the square grid (lib/colors/pattern.ts, decoded
	// from Čtrnáct's PT certificates to public/colors/squares-2-k*.json). Its presence routes /play + the
	// thumbnails to the colors renderer the way `freedraw` routes to the grid view — `renderCell` is a
	// throwaway, never drawn. Here `k` counts COLORED VERTEX classes: vertex orbits under the symmetries
	// that preserve the coloring — real vertex orbits (unlike freedraw's grid points), but of the COLORED
	// tiling, so every surface labels them "colored vertices".
	colors?: ColorPattern;
	// Spherical freedraw shelf only: Čtrnáct's freedraw on a Platonic solid (tools/ctrnact-oracle, decoded to
	// public/freedraw-ico/{solid}-k{k}.json). Its presence routes /play + the thumbnails to the three.js
	// ico-freedraw renderer (components/freedraw/ico-freedraw-canvas.tsx) the way `spherical` routes to the
	// solid sphere and `freedraw` to the 2D grid — `renderCell` is a throwaway here, never drawn. `solid` is
	// the Polyhedron id the renderer resolves vertices from; `k` counts VERTEX orbits (not grid points).
	sphericalFreedraw?: { solid: string; k: number; pattern: IcoPattern };
	// Hyperbolic edge-system shelf only: Čtrnáct's freedraw moved to H² (tools/ctrnact-oracle/develop_hyp_edges.py,
	// decoded to public/hyperbolic-edges/e<base>-k<k>.json). Its presence routes /play + the thumbnails to the
	// developed-edge renderer (HyperbolicDeveloper.developEdges + drawDevelopedEdgePatch) the way `freedraw`
	// routes to the 2D grid and `developed` to the Poincaré disk. Lives in the freedraw CLASS but the HYPERBOLIC
	// geometry, with the base tiling as the sub-axis — the exact parallel of spherical freedraw (freedraw class,
	// spherical geometry, solid sub-axis). `renderCell` is a throwaway. `k` counts vertex orbits.
	hypEdges?: HypEdgesPattern;
	// Hyperbolic colored-tiling shelf only: an n-coloring of a regular {p,q} hyperbolic tiling
	// (tools/ctrnact-oracle/develop_hyp_colors.py → public/hyperbolic-colors/c<base>-k<k>.json). Its presence
	// routes /play + thumbnails to the per-pixel disk shader in colors mode (HyperbolicColorsCanvas). Lives in
	// the COLORS class, HYPERBOLIC geometry, with the base {p,q} as the sub-axis — the exact parallel of the
	// edge systems. `renderCell` is a throwaway; `k` counts colored vertex orbits.
	hypColors?: HypColorsPattern;
	// Spherical colored-tiling shelf only: an n-coloring of a Platonic solid
	// (tools/ctrnact-oracle/develop_sph_colors.py → public/spherical-colors/<solid>-k<k>.json). Its presence
	// routes /play + thumbnails to the three.js SphericalColorsCanvas the way `sphericalFreedraw` routes to the
	// ico renderer. Colors class, SPHERICAL geometry, solid sub-axis. `renderCell` is a throwaway; `k` counts
	// colored vertex orbits.
	sphColors?: { solid: string; k: number; pattern: SphColorsPattern };
	// Schwarz-triangle edge systems (tools/ctrnact-oracle/develop_schwarz.py → public/schwarz-{sph,hyp}/).
	// The freedraw object on the board cut by the mirrors of a (p,q,r) reflection group, in the two
	// curved geometries — the Euclidean member of the same family is the `sch236` planar-freedraw grid.
	// FREEDRAW class, spherical or hyperbolic geometry, the board as the sub-axis; `renderCell` is a
	// throwaway. Its presence routes /play + thumbnails to the sphere renderer (spherical, via
	// lib/render/sphSchwarz.ts → buildIcoFreedraw) or the developed-edge disk renderer (hyperbolic,
	// HyperbolicDeveloper.developEdges — which reads this shelf's per-dart alpha/elen/drawn arrays,
	// since a Schwarz tile is scalene and none of the three is derivable from polygon sizes).
	// `k` counts vertex orbits.
	schwarz?: SchwarzPattern;
	// Uniform-polyhedron edge systems (tools/ctrnact-oracle/develop_sph_edges.py → public/spherical-edges/).
	// The same object as `schwarz` on a spherical board and as `hypEdges` in H², on a third kind of board:
	// a prism, an antiprism, the truncated tetrahedron, the cuboctahedron or its gyro-twin J27. FREEDRAW
	// class, SPHERICAL geometry, the solid as the sub-axis; `renderCell` is a throwaway. Renders through
	// the very same adapter the Schwarz spheres use (lib/render/sphSchwarz.ts → buildIcoFreedraw) — the
	// only difference is that these boards mix face sizes, which that adapter never assumed away.
	// `k` counts vertex orbits.
	sphEdges?: SphEdgesPattern;
	// The 3.4.n.4 family of hyperbolic tilings by regular polygons (tools/ctrnact-oracle/develop_ai1.py →
	// public/hyperbolic-poly/hp<n>-k<k>.json). Not a decoration of anything: at the edge length 3.4.n.4
	// forces, the three closing vertex figures make k-uniform tilings out of {3, 4, n, 2n}-gons. TILINGS
	// class, HYPERBOLIC geometry, the board n as the sub-axis. Its presence routes /play + thumbnails to
	// HyperbolicDeveloper.developColors — whose contract (fill each face by its index, stroke every edge)
	// is exactly this object's, with the index being the face's polygon size. `renderCell` is a throwaway.
	hypPoly?: HypPolyPattern;
	// The SPHERICAL members of the same 3.4.n.4 family (tools/ctrnact-oracle/develop_ai1_sph.py →
	// public/spherical-poly/sp<n>-k<k>.json), n = 3, 4, 5. TILINGS class, SPHERICAL geometry, the board n
	// as the sub-axis. Its presence routes /play + thumbnails to the three.js sphere through
	// lib/render/sphPoly.ts, which groups the faces by POLYGON SIZE — the same fill rule the hyperbolic
	// half uses on the disk. `renderCell` is a throwaway.
	sphPoly?: SphPolyPattern;
	// EDGE systems on a PARAMETRIC pentagon (tools/ctrnact-oracle/develop_pent_edges.py →
	// public/pentagon-edges/pe<type>-k<k>.json). EDGES class, EUCLIDEAN geometry. Unlike every other
	// shelf this record carries NO geometry: the tile is a Kershner type 1 pentagon with five free
	// parameters, so /play solves the board at the live slider point and re-develops
	// (lib/pentagon/edgeDevelop.ts). `renderCell` is a throwaway.
	pentEdges?: PentEdgeRecord;
	// EDGE systems on a PARAMETRIC ISOHEDRAL tile (tools/ctrnact-oracle/develop_ih_edges.py →
	// public/isohedral-edges/ie<nn>-k<k>.json). EDGES class, EUCLIDEAN geometry. Carries no geometry
	// either, and for the same reason as `pentEdges` — but where that board needed its own closure
	// solver, this one takes its tile from Tactile at the live parameter point, so the shelf generalises
	// to any of the 93 isohedral types Marek runs a solver on. `renderCell` is a throwaway.
	ihEdges?: IhEdgeRecord;
	geometry?: "euclidean" | "hyperbolic" | "spherical";
	// Hyperbolic shelf: which of the tilings sharing this vertex figure this one is, and how many there
	// are. In H2 the figure does not determine the tiling — 4.4.6.4.6.6 carries fourteen distinct ones —
	// so without an index the catalogue shows a run of identically labelled rows. Absent when unique.
	variant?: number;
	variants?: number;
	alphaRange?: [number, number]; // degrees; present ⇒ one-parameter family with an alpha slider
	// MERGED families (mixed shelf): this entry is one continuous sweep spliced from two exported halves,
	// cut where the flexing tile's alternating vertex passes 180° (concave star ↔ convex 2n-gon). `family`
	// stays the survivor's label — it is the shelf's grouping/search key — so the two halves' labels live
	// here, and `mergedFrom` records the pre-merge ids. Geometry is in `paramCell.segments`.
	familyHalves?: [string, string];
	mergedFrom?: string[];
	candidate?: boolean; // ctrnact-star only: not in Myers' enumeration — candidate new tiling
	preview?: boolean; // ctrnact-star only: from a PARTIAL (still-running) solve — incomplete, uncertified
	// Historical first-discoverer of this tiling (Kepler, Krötenheerdt, Chavey, Galebach, Čtrnáct,
	// Joseph Myers, Alessandro Longo). One attribute, orthogonal to certification.
	discoverer: string;
	// Rigorous completeness status of this tiling's enumeration level:
	//   proven      — this work's method has a completeness certificate (regular k≤3)
	//   reproduced  — count matches a published enumeration, not independently proven here
	//   candidate   — surfaced by this work; completeness / literature-novelty not established
	// Absent on the convex-irregular demo shelf — those tilings make no completeness claim, so they're
	// excluded from the certification facet, not assigned a misleading status.
	certification?: Certification;
	// Convex-irregular shelf only: true iff every composite tile it uses dissects into regular pieces (the
	// decomposable palette); false iff it uses a non-decomposable composite. Absent on every other source.
	decomposableOnly?: boolean;
	// Polyomino shelf only: which polyomino ORDER this tiling's tiles belong to — the sub-class facet
	// (Tetrominoes now; Pentominoes etc. later). Absent on every other source.
	polyominoOrder?: "tetromino";
	// Islamic shelf only: which of Bonner's design systems the underlying tessellation belongs to — the
	// sub-class facet (see docs/ISLAMIC_TILINGS.md). Absent on every other source.
	islamicSystem?: IslamicSystem;
	// Isotoxal shelf only: true iff the tiling uses a convex isotoxal tile NOT expressible on ζ₁₂ (i.e. not
	// one of the 60/120 rhombus, 90/150 hexagon, 120/150 octagon the convex-irregular enumeration already reached)
	// — the genuinely new tilings the ζ₂₄ grid unlocks. Absent on every other source.
	offGrid?: boolean;
	note?: string; // free-text provenance caveat (convex-irregular demo: counts are illustrative, not all-and-only)
	// Present on family entries: the proven parametric cell driving the /play alpha slider
	// (lib/utils/paramCell.ts). renderCell then holds the default-alpha evaluation (thumbnails).
	paramCell?: ParametricCellData;
	exactSource?: ExactCellSource; // exact cyclotomic cell for the symmetry overlay (added 2026-07)

	// Vertex-type classification (build-computed, 2026-07). k counts vertex ORBITS; m counts DISTINCT
	// vertex configurations among them (m ≤ k). `partition` is the multiplicities of those distinct
	// configs, descending, summing to k — e.g. m=3, partition [5,1,1] is the "511" group at k=7.
	// Absent when a source has no per-orbit config data (never guessed; the tiling is then excluded from
	// M/partition filters). m === k is the Krötenheerdt (maximal) class.
	m?: number;
	partition?: number[];
	// Exact wallpaper symmetry — REGULAR tilings only (WallpaperSymmetry needs exact convex-tile
	// intersection; star tiles are non-convex ⇒ omitted, NOTES §9.4). Absent for every star tiling.
	wallpaperGroup?: WallpaperGroup;
	latticeShape?: LatticeShape;
}

