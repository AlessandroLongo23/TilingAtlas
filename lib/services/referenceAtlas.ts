/**
 * Redirect a link that names a family absorbed by a merge (or by an α-reversal de-duplication) onto the
 * entry that now carries it, moving the shared angle with it: `u = c + m·α`.
 *
 * Generated by `scripts/build-mixed-atlas.ts` into `mergedFamilyAliases.json`, imported statically so this
 * resolves synchronously while the URL is being parsed — before any shelf has loaded.
 *
 * Only ABSORBED ids are remapped. A merge survivor keeps its id while its slider changes meaning (α became
 * θ or a sweep angle), and there `α=45` and `u=45` are the same string: an old link to it lands wherever
 * the ordinary range clamp puts it, which is a real member of the same family. Guessing instead would
 * silently move the view, so it is left alone.
 */
export function resolveMergedFamilyKey(state: { tiling: string | null; alphas: number[] | null }): {
	tiling: string | null;
	alphas: number[] | null;
} {
	// A coupled family absorbed several 1-D slices of itself, so the redirect goes from ONE angle to a
	// PAIR: the slice's seat in the region, plus how far along its own line the old α had travelled.
	const coupled = state.tiling ? COUPLED_FAMILY_ALIASES[state.tiling] : undefined;
	// Only a SINGLE angle is in the old coordinate. A link that already carries the pair is in the new one
	// (the survivor is aliased to itself, so without this guard every round-trip would remap its own output).
	if (coupled && (state.alphas?.length ?? 0) <= 1) {
		const a = state.alphas?.[0];
		const t = a != null && Number.isFinite(a) ? (a - coupled.fromAlpha0Deg) / 15 : 0;
		return {
			tiling: coupled.to,
			alphas: coupled.survivorAlpha0Deg.map(
				(a0, p) => a0 + 15 * (coupled.deltaUnits[p] + t * coupled.axisUnits[p]),
			),
		};
	}
	const alias = state.tiling ? MERGED_FAMILY_ALIASES[state.tiling] : undefined;
	if (!alias) return state;
	const a = state.alphas?.[0];
	const alphas =
		a != null && Number.isFinite(a) ? [alias.uOf.c + alias.uOf.m * a, ...(state.alphas ?? []).slice(1)] : state.alphas;
	return { tiling: alias.to, alphas };
}

type MergedAliasTable = Record<string, { to: string; uOf: { m: number; c: number } }>;
type CoupledAliasTable = Record<string, {
	to: string;
	fromAlpha0Deg: number;
	deltaUnits: number[];
	axisUnits: number[];
	survivorAlpha0Deg: number[];
}>;

const COUPLED_FAMILY_ALIASES: CoupledAliasTable = COUPLED_ALIASES_MIXED as CoupledAliasTable;

const MERGED_FAMILY_ALIASES: MergedAliasTable = {
	...(MERGED_ALIASES_MIXED as MergedAliasTable),
	...(MERGED_ALIASES_ISOTOXAL as MergedAliasTable),
};

// Isotoxal shelf only: how many INDEPENDENT free angles the family flexes on (its paramCell slider count
// P). 1 ⇒ a single isotoxal tile flexes (α-family); 2 ⇒ two isotoxal tiles flex on their own (α, β-family).
// Null for any non-isotoxal tiling, or an isotoxal record missing its parametric cell — those never match
// the Shape facet, matching the exclude-the-unclassified ethos used by the M/partition filters.
export function isotoxalParamCount(t: Pick<ReferenceTiling, "source" | "paramCell">): 1 | 2 | null {
	if (t.source !== "isotoxal") return null;
	const n = t.paramCell?.params?.length;
	return n === 1 || n === 2 ? n : null;
}

// Canonical partition key for display + filtering: digits joined ("511"), switching to a "."
// separator if any part reaches 10 so "10,1" never collides with "1,0,1". Null when unclassified.
export function partitionKeyOf(t: Pick<ReferenceTiling, "partition">): string | null {
	if (!t.partition?.length) return null;
	const sep = t.partition.some((p) => p >= 10) ? "." : "";
	return t.partition.join(sep);
}

// Krötenheerdt (maximal): every orbit has a distinct vertex config, i.e. m === k. False when unclassified.
export function isMaximal(t: Pick<ReferenceTiling, "m" | "k">): boolean {
	return t.m != null && t.m === t.k;
}

// ── hyperbolic interval facets (2026-07-23) ───────────────────────────────────────────────────────
// The scalars behind the /library hyperbolic sliders, parsed from the family label ("3.4.4.8 +
// 3.4.8.4"). Both are MAXIMA over the k vertex figures — the same axes the (k,p,v) sweep enumerates
// by (palette p = largest polygon anywhere, valence v = most edges at any vertex) — so a slider's
// upper bound reads exactly as a sweep cell's bound. Cached per id: the matcher runs over all 28k+
// entries on every filter keystroke, and the label never changes after load.
const hypFacetCache = new Map<string, { valence: number; polygon: number } | null>();
export function hyperbolicFacetsOf(
	t: Pick<ReferenceTiling, "id" | "source" | "family">,
): { valence: number; polygon: number } | null {
	if (t.source !== "hyperbolic") return null;
	const cached = hypFacetCache.get(t.id);
	if (cached !== undefined) return cached;
	let valence = 0;
	let polygon = 0;
	for (const figure of t.family.split("+")) {
		const ns = figure
			.split(".")
			.map((s) => Number(s.trim()))
			.filter((n) => Number.isInteger(n) && n >= 3);
		if (ns.length) {
			valence = Math.max(valence, ns.length);
			polygon = Math.max(polygon, ...ns);
		}
	}
	const facets = valence >= 3 ? { valence, polygon } : null;
	hypFacetCache.set(t.id, facets);
	return facets;
}

export interface ReferenceFilter {
	// The geometry axis — the library's top-level split, one level above tileClass. When set, only tilings
	// of this geometry match. The Euclidean-only sub-filters (tileClass, star, lattice, wallpaper group)
	// are meaningless off the plane, so the shelf hides them for hyperbolic/spherical.
	geometry?: Geometry;
	// The decoration axis — WHAT is catalogued, between geometry and tileClass. Present in every geometry.
	// When set to "tilings" the tileClass chips describe the shape shelves; the other two segments hold one
	// class each (freedraw, colors), so their own facets take over instead.
	decoration?: Decoration;
	kValue?: number; // single vertex-orbit count; unset = every k
	tileClass?: TileClass; // regular polygons only / star-bearing only / composite-tile demo
	// Scaled shelf sub-class: "s12" keeps only tilings within sides {1,2} (the former Doubled class);
	// "s123" keeps only tilings that use a side-3 tile. Non-scaled tilings never match while this is active.
	scaledScaleSet?: "s12" | "s123";
	// Polyomino shelf sub-class: keep only tilings whose tiles are of this polyomino order ("tetromino" today).
	// Non-polyomino tilings never match while this is active.
	polyominoOrder?: "tetromino";
	// Islamic shelf sub-class: keep only tilings in this Bonner design system. Non-Islamic tilings never
	// match while this is active.
	islamicSystem?: IslamicSystem;
	// Freedraw shelf sub-class: keep only patterns whose faces are all finite / include a strip / include an
	// unbounded sheet / include a polyomino with holes. Non-freedraw tilings never match while this is active.
	freedrawKind?: FreedrawKind;
	// Freedraw shelf sub-class, one level above the kind: which grid the edge subset decorates. Non-freedraw
	// tilings never match while this is active.
	freedrawGrid?: FreedrawGrid;
	// Colors shelf sub-class: which grid the coloring lives on. Non-colors tilings never match while
	// this is active.
	colorsGrid?: ColorsGrid;
	// Colors shelf sub-class: how many colors the palette has (2 or 3 so far). Non-colors tilings never
	// match while this is active.
	colorsCount?: number;
	// Freedraw shelf facet: keep only patterns that are tilings by regular polygons (the k-uniform
	// subfamily), or that contain a given regular polygon. Non-freedraw tilings never match while active.
	freedrawRegular?: FreedrawRegular;
	// Convex-irregular shelf facet: keep only decomposable-family or only uses-non-decomposable tilings.
	// Any tiling outside that class (decomposableOnly undefined) is EXCLUDED while this is active.
	convexDecomp?: "decomposable" | "non-decomposable";
	mValue?: number; // single distinct-vertex-config count; unclassified tilings never match
	partitionKey?: string; // single partition key (e.g. "511"); unclassified tilings never match
	maximalOnly?: boolean; // Krötenheerdt: keep only m === k
	// Marek's five levels of increasing complexity (lib/tilings/tiling-level.ts). A CURVED-geometry
	// facet: it needs per-orbit vertex configurations, which only the hyperbolic and spherical shelves
	// ship, and its top rung means nothing in E², where every combination shares one edge length for
	// free. Anything the ladder does not describe — every edge system, colouring and freedraw pattern,
	// and the whole Euclidean catalogue — is EXCLUDED while this is active, never silently passed.
	levels?: TilingLevel[];
	starFolds?: number[]; // keep tilings using at least one of these star folds
	parametric?: "rigid" | "family"; // rigid (no α) / one-parameter α-family
	isotoxalShape?: "alpha" | "alpha-beta"; // isotoxal only: 1 free angle (α) vs 2 independent (α, β)
	wallpaperGroups?: WallpaperGroup[]; // exact group; unclassified (all stars) never match
	latticeShapes?: LatticeShape[]; // exact lattice shape; unclassified (all stars) never match
	discoverers?: string[]; // each entry's discoverer must be in this set
	certifications?: Certification[]; // proven / reproduced / candidate
	polygonNames?: string[]; // each must appear in the tiling's family label
	query?: string; // free-text substring match on id or family (e.g. "4j5_5b2" or "3.6")
	// Hyperbolic shelf facets, each an inclusive interval [lo, hi] driven by an IntervalSlider. The
	// scalars are hyperbolicFacetsOf (valence/polygon maxima over the vertex figures) and the merged
	// forced edge length ℓ. Non-hyperbolic tilings never match while one of these is active.
	hypValence?: [number, number]; // most edges at any vertex (v of the sweep)
	hypPolygon?: [number, number]; // largest polygon in any figure (palette p of the sweep)
	hypEdge?: [number, number]; // forced edge length ℓ (Poincaré metric)
}

export function matchesReferenceFilters(t: ReferenceTiling, f: ReferenceFilter): boolean {
	if (f.geometry && geometryOf(t) !== f.geometry) return false;
	if (f.decoration && decorationOf(t) !== f.decoration) return false;
	if (f.kValue != null && t.k !== f.kValue) return false;
	if (f.tileClass && tileClassOf(t) !== f.tileClass) return false;
	if (f.scaledScaleSet) {
		const ms = scaledMaxScaleOf(t);
		if (ms == null) return false; // non-scaled tilings never match the scale-set facet
		if (f.scaledScaleSet === "s12" && ms > 2) return false;
		if (f.scaledScaleSet === "s123" && ms < 3) return false;
	}
	if (f.polyominoOrder) {
		if (polyominoOrderOf(t) !== f.polyominoOrder) return false; // non-polyomino tilings never match the order facet
	}
	if (f.islamicSystem) {
		if (islamicSystemOf(t) !== f.islamicSystem) return false; // non-Islamic tilings never match the system facet
	}
	if (f.freedrawKind) {
		const s = freedrawStatsOf(t);
		if (!s || !matchesFreedrawKind(s, f.freedrawKind)) return false; // non-freedraw never matches the kind facet
	}
	if (f.freedrawGrid) {
		if (freedrawGridOf(t) !== f.freedrawGrid) return false; // non-freedraw never matches the grid facet
	}
	if (f.colorsGrid) {
		if (colorsGridOf(t) !== f.colorsGrid) return false; // non-colors never matches the grid facet
	}
	if (f.colorsCount) {
		if (colorsCountOf(t) !== f.colorsCount) return false; // non-colors never matches the palette facet
	}
	if (f.freedrawRegular) {
		const r = freedrawRegularOf(t);
		if (!r || !matchesFreedrawRegular(r, f.freedrawRegular)) return false; // non-freedraw never matches
	}
	if (f.convexDecomp) {
		if (t.decomposableOnly == null) return false; // tilings outside the convex-irregular class never match this facet
		if (f.convexDecomp === "decomposable" && !t.decomposableOnly) return false;
		if (f.convexDecomp === "non-decomposable" && t.decomposableOnly) return false;
	}
	// M/partition/maximal: an active filter EXCLUDES unclassified tilings instead of matching them —
	// completeness ethos, we never silently pass a tiling whose classification we don't have.
	if (f.mValue != null && t.m !== f.mValue) return false;
	if (f.partitionKey != null && partitionKeyOf(t) !== f.partitionKey) return false;
	if (f.maximalOnly && !isMaximal(t)) return false;
	if (f.levels?.length) {
		const lv = tilingLevel(t);
		if (lv == null || !f.levels.includes(lv)) return false;
	}
	if (f.starFolds?.length) {
		const folds = starFoldsOf(t);
		if (!f.starFolds.some((n) => folds.includes(n))) return false;
	}
	if (f.parametric) {
		const isFam = isParametric(t);
		if (f.parametric === "family" && !isFam) return false;
		if (f.parametric === "rigid" && isFam) return false;
	}
	if (f.isotoxalShape) {
		const p = isotoxalParamCount(t);
		if (f.isotoxalShape === "alpha" && p !== 1) return false;
		if (f.isotoxalShape === "alpha-beta" && p !== 2) return false;
	}
	if (f.wallpaperGroups?.length && (t.wallpaperGroup == null || !f.wallpaperGroups.includes(t.wallpaperGroup))) return false;
	if (f.latticeShapes?.length && (t.latticeShape == null || !f.latticeShapes.includes(t.latticeShape))) return false;
	// Hyperbolic interval facets: an active one excludes everything outside the hyperbolic shelf (or
	// missing the scalar) — same never-silently-pass ethos as M/partition above.
	if (f.hypValence || f.hypPolygon) {
		const hf = hyperbolicFacetsOf(t);
		if (!hf) return false;
		if (f.hypValence && (hf.valence < f.hypValence[0] || hf.valence > f.hypValence[1])) return false;
		if (f.hypPolygon && (hf.polygon < f.hypPolygon[0] || hf.polygon > f.hypPolygon[1])) return false;
	}
	if (f.hypEdge) {
		// The slider's bounds are the data's min/max rounded outward to 0.01, and ε absorbs the float
		// dust of 0.01-stepped stops, so an entry sitting exactly on a bound always matches.
		if (t.source !== "hyperbolic" || t.edge == null) return false;
		if (t.edge < f.hypEdge[0] - 1e-9 || t.edge > f.hypEdge[1] + 1e-9) return false;
	}
	if (f.discoverers?.length && !f.discoverers.includes(t.discoverer)) return false;
	if (f.certifications?.length && (t.certification == null || !f.certifications.includes(t.certification))) return false;
	if (f.polygonNames?.length) {
		const fam = t.family.split(".").map((s) => s.trim());
		if (!f.polygonNames.every((n) => fam.includes(n))) return false;
	}
	if (f.query?.trim()) {
		const q = f.query.trim().toLowerCase();
		if (!t.id.toLowerCase().includes(q) && !t.family.toLowerCase().includes(q)) return false;
	}
	return true;
}

