// Freedraw patterns ship as their own catalogue (public/freedraw/solutions.json — the same file the
// standalone /freedraw page reads), not as a pre-baked reference-atlas-*.json. There is nothing to bake:
// the pattern IS the record, and wrapping it in a build script would only duplicate 16 kB and give the two
// copies a way to drift. So the adaptation happens here, at load, the way the hyperbolic `edge` merge does.
//
// `renderCell` is a deliberate throwaway — every consumer that would draw it branches on `freedraw` first
// (thumbnails, /play canvas), exactly as they branch on `developed`/`spherical`.
const FREEDRAW_EMPTY_CELL = { cellPolygons: [], basis: [[1, 0], [0, 1]] } as unknown as TranslationalCellData;

function freedrawToReference(p: FreedrawPattern): ReferenceTiling {
	const stats = summarise(analyseFaces(p));
	freedrawStatsCache.set(p.id, stats);
	const grid = gridOf(p);
	// Certification tracks how each SLICE was obtained. Square k ≤ 3 and triangle k = 1 were enumerated
	// independently here AND reproduced from Čtrnáct's solver — matched counts, hence "reproduced".
	// Square k = 4, triangle k ≥ 2, and the whole combined grid exist only as decodes of his
	// certificates (the decoder is validated bijectively on the slices above, and the combined grid's
	// digon-free slice reproduces the known 4/7/17 uniform square-triangle tilings, but no independent
	// enumeration reaches the rest), so they carry "candidate" until something independent does.
	// Schwarz 236 is "candidate" on the same footing. What its decode DOES check: all 43 certificates
	// develop with no failures, every one of the 636 emitted faces measures as an exact 30-60-90
	// triangle with sides 1 : √3 : 2, and the nothing-drawn slice is a single pattern at k=3 — the bare
	// Schwarz tiling, which is the only thing it could be. That is the decoder verifying itself, not an
	// independent enumeration of the family.
	const verified = grid === "square" ? p.k <= 3 : grid === "triangle" ? p.k <= 1 : false;
	return {
		id: p.id,
		source: "freedraw",
		k: p.k,
		family: freedrawFamilyLabel(stats, grid),
		renderCell: FREEDRAW_EMPTY_CELL,
		freedraw: p,
		geometry: "euclidean",
		discoverer: "Marek Čtrnáct",
		certification: verified ? "reproduced" : "candidate",
	};
}

