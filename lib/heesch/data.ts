// Heesch numbers: how many complete rings of copies can surround a shape that does not tile the plane.
//
// The grid censuses were computed with Craig Kaplan's heesch-sat (github.com/isohedral/heesch-sat); the
// polyominoes past 11 cells, and the counts on every size, with this atlas's own engine (omino_census
// classifies, free_heesch settles what it leaves). tools/heesch/build_data.py packs them and re-audits
// each witness patch (congruent copies, no overlap, every corona surrounding the one before it, each
// prefix a closed disk) before it writes a file. The solver outputs live in experiments/results/heesch/.
//
// TWO NUMBERS PER SHAPE, because the definition is not settled and the two differ by at most one.
// `hc` is the strict Grünbaum–Shephard number: every corona, with everything inside it, is a closed
// disk. `hh` lets the OUTERMOST corona enclose holes. Kaplan's tables carry both; so does this.

import type { ParametricCell } from "@/lib/hooks/useParametricTilingCanvas";
import { buildCellMesh } from "@/lib/render/buildCellMesh";
import type { RawPolygon } from "@/lib/utils/renderTiling";
import GRIDS from "./grids.json";

// A GRID IS ONE TABLE (grids.json, generated by tools/heesch/gen_grids.py from the solver's own grid
// classes): a translation lattice, one cell per translation class with its corners as offsets from the
// cell's point, and the map to the page. Cells are integer points in the solver's coordinates, where
// its transforms act, so every grid shares every line below. The audit reads the same file.
export type HeeschGridId = keyof typeof GRIDS;
type GridDef = { den: number; period: number[][]; page: number[][]; cells: { at: number[]; verts: number[][] }[] };
const grid = (g: HeeschGridId) => GRIDS[g] as GridDef;
export const HEESCH_GRIDS = Object.keys(GRIDS) as HeeschGridId[];
export const heeschGridLabel = (g: HeeschGridId) => GRIDS[g].label;
/**
 * How copies are placed on a grid, as the page words it, and the caveat that goes with it.
 *
 * "restriction" is where placing copies only on the grid is the solver's limit, not the literature's
 * convention: there a number is a lower bound, and a shape listed may tile off the grid. "free" is no
 * grid at all: unit squares and triangles whose copies meet edge to edge anywhere.
 */
export const gridPlacement = (g: HeeschGridId) => (GRIDS[g].aligned === "free" ? "edge to edge, no grid" : "aligned to the grid");
export function gridCaveat(g: HeeschGridId): string | null {
	if (GRIDS[g].aligned === "restriction")
		return "Copies are placed on the grid only. A number here is a lower bound, and a shape listed may tile with copies off the grid.";
	if (GRIDS[g].aligned === "free")
		return "Copies meet edge to edge, on no grid. Shapes that closed every corona the search asked for are left out: they tile, or go deeper than it looked.";
	return null;
}
/** "9-omino", "10-iamond", "7-hex". */
export const polyformName = (s: HeeschShape) => `${s.cells}-${GRIDS[s.grid].noun}`;
/** "9-ominoes", "10-iamonds", "7-hexes". */
export const polyformPlural = (g: HeeschGridId, cells: number) => {
	const noun = GRIDS[g].noun;
	return `${cells}-${noun}${/[ox]$/.test(noun) ? "es" : "s"}`;
};

/** Solver coordinates to the page, scaled so the shortest cell edge is one unit on every grid. */
function toPage(g: HeeschGridId, x: number, y: number): { x: number; y: number } {
	const [[a, b], [c, d]] = grid(g).page;
	return { x: a * x + b * y, y: c * x + d * y };
}

export type HeeschDefinition = "strict" | "holes";

export interface HeeschShape {
	grid: HeeschGridId;
	cells: number;
	/** The tile's outline, flattened [x0, y0, x1, y1, …], counter-clockwise, straight vertices dropped,
	 *  in units of 1/den of the solver's coordinates (so most grids store integers). */
	o: number[];
	/** Strict Heesch number, and the number with holes allowed in the outermost corona; absent on a
	 *  shape that tiles the plane (its number is infinite), which carries `p` instead. */
	hc?: number;
	hh?: number;
	/** A tiler's tiling: a lattice basis [ux, uy, vx, vy] in cell coordinates and the copies of one
	 *  period, six numbers each (the cell map), so that the copies and their translates tile the plane. */
	p?: { l: number[]; k: number[] };
	/** Witness patches, seven numbers a tile: corona, then a, b, c, d, e, f of the cell map
	 *  (x, y) → (ax+by+c, dx+ey+f).
	 *  `w` is the strict patch (absent at hc = 0), `wh` the one with holes (absent when hh = hc). */
	w?: number[];
	wh?: number[];
	/** The seams between the shape's cells, as page segments, where no grid table can supply them. */
	s?: number[];
	name?: string;
	credit?: string;
}

export interface HeeschSetInfo {
	id: string;
	grid: HeeschGridId;
	cells: number;
	count: number;
	/** Shapes per Heesch number, index = H, under each definition. */
	hc: number[];
	hh: number[];
	/** Set while a census is still running: how many of its `of` shapes have been searched so far. */
	searched?: number;
	of?: number;
	/** The whole census of the size, where the set lists only part of it: every hole-free shape counted,
	 *  `hh` by Heesch number with holes allowed, the shapes listed being those from `listedFrom` up.
	 *  `unresolved` tilers are counted by no proof here; `slices` is [done, of] while it still runs. */
	census?: { holeFree: number; tilers: number; hh: number[]; unresolved?: number; listedFrom?: number; slices?: [number, number] };
	/** The size's tilers, with their tilings, in files `<id>-t<i>.json` of `shard` shapes each. */
	tilers?: { count: number; shard: number };
}

export interface HeeschIndex {
	sets: HeeschSetInfo[];
	named: number;
}

/** The set id of the hand-picked tiles, beside the per-size censuses. */
