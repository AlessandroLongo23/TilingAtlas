const cache = new Map<string, Promise<unknown>>();
function load<T>(file: string): Promise<T | null> {
	let p = cache.get(file) as Promise<T | null> | undefined;
	if (!p) {
		p = fetch(`/heesch/${file}.json`)
			.then((res) => (res.ok ? (res.json() as Promise<T>) : null))
			.catch(() => null);
		cache.set(file, p);
	}
	return p;
}

export const loadHeeschIndex = () => load<HeeschIndex>("index");
/** A set's shapes, each stamped with its grid: a census file names the grid once, a named tile carries its own. */
export const loadHeeschSet = (id: string) =>
	load<{ grid?: HeeschGridId; shapes: HeeschShape[] }>(id).then(
		(d) => d?.shapes.map((s) => (s.grid ? s : { ...s, grid: d.grid ?? "omino" })) ?? null,
	);

/** One file of a size's tilers. */
export const loadHeeschTilers = (id: string, shard: number) =>
	load<{ grid: HeeschGridId; shapes: HeeschShape[] }>(`${id}-t${shard}`).then((d) => d?.shapes.map((s) => ({ ...s, grid: d.grid })) ?? null);

/** The tile's outline in solver coordinates, as a vertex ring. */
function outlineRing(s: HeeschShape): { x: number; y: number }[] {
	const { den } = grid(s.grid);
	const ring = [];
	for (let i = 0; i < s.o.length; i += 2) ring.push({ x: s.o[i] / den, y: s.o[i + 1] / den });
	return ring;
}

/** The tile's outline on the page, as a vertex ring. */
export const outlinePage = (s: HeeschShape) => outlineRing(s).map((v) => toPage(s.grid, v.x, v.y));

/** Infinity for a shape that tiles the plane. */
export const heeschNumber = (s: HeeschShape, def: HeeschDefinition) => (s.p ? Infinity : ((def === "strict" ? s.hc : s.hh) ?? 0));

/** One hue per corona, index = corona (0 is the centre tile), walking the wheel so neighbouring rings
 *  never sit on neighbouring hues. */
const CORONA_HUES = [0, 205, 95, 275, 45, 160, 320, 240];
export const coronaHue = (level: number) => CORONA_HUES[level % CORONA_HUES.length];

/** Tiles per corona in the patch a definition shows; index = corona, and [1] when there is no patch. */
export function ringSizes(s: HeeschShape, def: HeeschDefinition): number[] {
	const w = witness(s, def);
	const out = [1];
	for (let i = 7; i < w.length; i += 7) out[w[i]] = (out[w[i]] ?? 0) + 1;
	return out;
}

/** The patch behind a definition's number. With holes allowed that is `wh`, or the strict patch when
 *  the two numbers agree. Empty for a shape nothing can surround. */
function witness(s: HeeschShape, def: HeeschDefinition): number[] {
	return (def === "holes" ? (s.wh ?? s.w) : s.w) ?? [];
}

/**
 * The seams between a tile's unit cells: every edge two of its cells share, as page segments
 * flattened [x0, y0, x1, y1, …]. Drawn over the centre tile so the polyform can be read off it.
 *
 * Read back off the outline, so the data files do not carry the cells twice: a cell is in the tile
 * when its centroid is inside the outline (even-odd crossing count along +x). An edge listed by two
 * member cells is a seam.
 */
export function cellSeams(s: HeeschShape): number[] {
	if (s.s) return s.s;
	const { den, period, cells } = grid(s.grid);
	const [[ax, ay], [bx, by]] = period;
	const det = ax * by - ay * bx;
	// The cell kind at an integer point: its class modulo the translation lattice, if it has one.
	const kindAt = (x: number, y: number) => {
		const u = Math.floor((x * by - y * bx) / det), v = Math.floor((ax * y - ay * x) / det);
		const rx = x - u * ax - v * bx, ry = y - u * ay - v * by;
		return cells.find((c) => c.at[0] === rx && c.at[1] === ry);
	};
	const ring = outlineRing(s);
	const inside = (x: number, y: number) => {
		let hit = false;
		for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
			const p = ring[i], q = ring[j];
			if (p.y > y !== q.y > y && x < p.x + ((y - p.y) * (q.x - p.x)) / (q.y - p.y)) hit = !hit;
		}
		return hit;
	};
	let minx = Infinity, miny = Infinity, maxx = -Infinity, maxy = -Infinity;
	for (const v of ring) {
		minx = Math.min(minx, v.x);
		maxx = Math.max(maxx, v.x);
		miny = Math.min(miny, v.y);
		maxy = Math.max(maxy, v.y);
	}
	// A cell's point can sit a few units from its corners (a drafter's by three), so look past the box.
	const reach = 4;
	const seen = new Set<string>();
	const seams: number[] = [];
	for (let x = Math.floor(minx) - reach; x <= Math.ceil(maxx) + reach; x++)
		for (let y = Math.floor(miny) - reach; y <= Math.ceil(maxy) + reach; y++) {
			const kind = kindAt(x, y);
			if (!kind) continue;
			const verts = kind.verts.map(([vx, vy]) => [x + vx / den, y + vy / den]);
			const cx = verts.reduce((t, v) => t + v[0], 0) / verts.length, cy = verts.reduce((t, v) => t + v[1], 0) / verts.length;
			if (!inside(cx, cy)) continue;
			verts.forEach((a, k) => {
				const b = verts[(k + 1) % verts.length];
				const ka = `${a[0].toFixed(4)},${a[1].toFixed(4)}`, kb = `${b[0].toFixed(4)},${b[1].toFixed(4)}`;
				const key = ka < kb ? `${ka}|${kb}` : `${kb}|${ka}`;
				if (!seen.has(key)) return void seen.add(key);
				const p = toPage(s.grid, a[0], a[1]), q = toPage(s.grid, b[0], b[1]);
				seams.push(p.x, p.y, q.x, q.y);
			});
		}
	return seams;
}

/** The witness patch out to `upTo` coronas as polygons the flat renderers draw. The centre tile is
 *  always first and always in its own coordinates (the solver places it with the identity). */
export function patchPolygons(s: HeeschShape, def: HeeschDefinition, upTo: number): RawPolygon[] {
	const w = witness(s, def);
	const tiles = w.length ? w : [0, 1, 0, 0, 0, 1, 0];
	const ring = outlineRing(s);
	const polys: RawPolygon[] = [];
	for (let i = 0; i < tiles.length; i += 7) {
		const [level, a, b, c, d, e, f] = tiles.slice(i, i + 7);
		if (level > upTo) continue;
		const vertices = ring.map((v) => toPage(s.grid, a * v.x + b * v.y + c, d * v.x + e * v.y + f));
		polys.push({ n: vertices.length, vertices, hue: coronaHue(level) });
	}
	return polys;
}

/** Tile diameters across the short side of a tiling's opening view. */
const TILING_HOME = 4;

/** Hues for a tiling's orientations, in order of first appearance. */
const ORIENTATION_HUES = [205, 45, 95, 320, 160, 275, 0, 240];

/** A tiler's tiling as one translational cell, for the renderer that repeats it over the whole view
 *  (the one /pentagons and /isohedral use): the copies of one period and the lattice, on the page. One
 *  hue per orientation of the tile: copies that are translates of each other share it, whichever
 *  symmetry of the tile made them. */
export function tilingCell(s: HeeschShape): ParametricCell | null {
	if (!s.p) return null;
	const ring = outlineRing(s);
	const hueOf = new Map<string, number>();
	const polygons: RawPolygon[] = [];
	for (let c = 0; c < s.p.k.length; c += 6) {
		const [a, b, e, d, f, g] = s.p.k.slice(c, c + 6);
		// An orientation is the copy's outline up to translation: its corners, less their minimum.
		const pts = ring.map((v) => [a * v.x + b * v.y, d * v.x + f * v.y]);
		const mx = Math.min(...pts.map((q) => q[0])), my = Math.min(...pts.map((q) => q[1]));
		const key = pts.map((q) => `${q[0] - mx},${q[1] - my}`).sort().join(" ");
		if (!hueOf.has(key)) hueOf.set(key, ORIENTATION_HUES[hueOf.size % ORIENTATION_HUES.length]);
		const vertices = pts.map((q) => toPage(s.grid, q[0] + e, q[1] + g));
		polygons.push({ n: vertices.length, vertices, hue: hueOf.get(key)! });
	}
	const [ux, uy, vx, vy] = s.p.l;
	const u = toPage(s.grid, ux, uy), w = toPage(s.grid, vx, vy);
	const v1: [number, number] = [u.x, u.y], v2: [number, number] = [w.x, w.y];
	const mesh = buildCellMesh({ cellPolygons: polygons, basis: [v1, v2] });
	if (!mesh) return null;
	const page = outlinePage(s);
	const cx = page.reduce((t, v) => t + v.x, 0) / page.length, cy = page.reduce((t, v) => t + v.y, 0) / page.length;
	const span = TILING_HOME * 2 * Math.max(...page.map((v) => Math.hypot(v.x - cx, v.y - cy)));
	return { polygons, mesh, v1, v2, home: { cx, cy, width: span, height: span } };
}
