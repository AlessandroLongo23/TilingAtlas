// The Johnson solids the Čtrnáct engine develops, from TWO developers, and the split is the point.
//
// The first twelve come from develop_spherical (k=2..8) and are all INSCRIBABLE, every vertex on one
// sphere, because each is reached from an inscribable uniform solid by an operation that preserves the
// circumsphere: GYRATION (rotating a cupola or rotunda about its axis) or DIMINISHMENT (slicing one
// off). That was not a choice, it was the method: developing on S² with a single edge arc can only
// ever produce a solid that HAS a circumsphere, so the elongated and augmented Johnson solids were
// structurally invisible and this file used to say they "never appear".
//
// The twenty-four below come from develop_euclid (2026-08-20), which solves for DIHEDRAL ANGLES in R³
// and assumes no sphere at all. Most have no circumsphere and could not have been developed by the old
// path at any k. Five — the pyramids J1, J2 and the cupolas J3, J4, J5 — do have one, and were missed
// for a different reason: their circumsphere puts a face on a great circle, which is the
// circumradius-π/2 boundary of regular_spherical_polygon.
//
// The last five are the 2-orbit DELTAHEDRA — J12, J13, J17, J51, J84 — and they were missing for a
// third reason, upstream of both developers. Three separate stages seeded a decision on the CORNER
// CLASS of a dart, which on an all-triangle alphabet is 0 for every dart of every block: the solver's
// minimality refinement deleted them at closure, the pruner's isomorphism test deleted whatever got
// past it, and develop_euclid's unfold() guessed a dart cycle's vertex word by matching face
// sequences, where every word matches every other. Fixed and gated by `make check-deltahedra`, which
// asserts the classical eight convex deltahedra (F = 4, 6, 8, 10, 12, 14, 16, 20 and none at 18).
// The hunt is written up in experiments/results/deltahedra-fix-2026-08-20.md.
//
// Each is a generic Polyhedron. The spherical set is the developer's exact unit-sphere output; the
// Euclidean set is centred on its vertex centroid and scaled so the farthest vertex sits at radius 1,
// since a solid with no circumsphere cannot be put on the unit sphere honestly.
// Generated by tools/ctrnact-oracle/gen_johnson_ts.py and gen_johnson_euclid.py.

